"""Build the reproducibility package: release/ with lockfile, hashes, manifest and run instructions."""
import hashlib, json, pathlib, subprocess, sys, datetime, platform

ROOT = pathlib.Path(__file__).resolve().parent
K = ROOT.parent
REL = K / "paper_rev" / "release"; REL.mkdir(parents=True, exist_ok=True)


def sha(p):
    h = hashlib.sha256()
    with open(p, "rb") as f:
        for b in iter(lambda: f.read(1 << 20), b""):
            h.update(b)
    return h.hexdigest()


# environment
freeze = subprocess.run([sys.executable, "-m", "pip", "freeze"], capture_output=True, text=True).stdout
(REL / "environment.lock.txt").write_text(freeze)
try:
    gpu = subprocess.run(["nvidia-smi", "--query-gpu=name,driver_version", "--format=csv,noheader"], capture_output=True, text=True).stdout.strip()
except Exception:
    gpu = "n/a"
env = {"python": sys.version, "platform": platform.platform(), "gpu": gpu, "built": datetime.datetime.now().isoformat(timespec="seconds"),
       "git_branch": subprocess.run(["git", "-C", str(ROOT), "branch", "--show-current"], capture_output=True, text=True).stdout.strip(),
       "git_commit": subprocess.run(["git", "-C", str(ROOT), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()}
(REL / "environment.json").write_text(json.dumps(env, indent=1))

# hashes
hashes = {}
for folder in ("data", "repo/results"):
    for p in sorted((K / folder).glob("*")):
        if p.is_file():
            hashes[f"{folder}/{p.name}"] = {"sha256": sha(p), "bytes": p.stat().st_size}
for p in sorted((K / "raw").rglob("*")):
    if p.is_file() and p.stat().st_size > 0 and "docs" not in p.parts:
        hashes[str(p.relative_to(K)).replace("\\", "/")] = {"sha256": sha(p), "bytes": p.stat().st_size}
(REL / "hashes.json").write_text(json.dumps(hashes, indent=1))

